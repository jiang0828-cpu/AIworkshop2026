async function addTask(input = "编写代码", assisted = false) {
  const agents = await db.dailyAgent.findMany();
  const draft = rulePlan(input, "2026-10-01", assisted ? agents : [])[0];
  if (!assisted) draft.steps = draft.steps.map((step) => ({ ...step, agentId: step.assignee === "ai" ? agents[0].id : null }));
  await withDailyLock(db, () => saveTasks(db, "2026-10-01", [draft], input, "test"));
  return (await getDailyView(db, "2026-10-01", config)).plan!.tasks.at(-1)!;
}
function humanDraft(title: string, date: string) {
  const draft = rulePlan(title, date, [])[0];
  return { ...draft, lane: "A" as const, steps: draft.steps.map((step) => ({ ...step, assignee: "human" as const, agentId: null })) };
}
